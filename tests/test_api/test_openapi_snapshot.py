"""`frontend/openapi.json` là ranh giới DUY NHẤT giữa backend và web (ADR-008, ADR-009).

Đổi model / endpoint mà quên chụp lại hợp đồng thì type của web lệch backend mà không ai biết.
Sửa khi test đỏ:  python scripts/export_openapi.py  rồi  (cd frontend && npm run gen:api)
"""

import json
from pathlib import Path

from scripts.export_openapi import SNAPSHOT_PATH, render_openapi
from src.models.events import WS_PAYLOAD_MODELS, WsMessageType

ROOT = Path(__file__).resolve().parents[2]


def test_committed_snapshot_matches_running_app():
    assert SNAPSHOT_PATH.is_file(), "Thiếu frontend/openapi.json — chạy: python scripts/export_openapi.py"
    assert SNAPSHOT_PATH.read_text(encoding="utf-8") == render_openapi(), (
        "frontend/openapi.json đã cũ — chạy: python scripts/export_openapi.py rồi `npm run gen:api` trong frontend/"
    )


def test_generated_types_are_newer_than_nothing():
    """File type của web phải tồn tại và được sinh từ snapshot (không gõ tay DTO)."""
    schema = ROOT / "frontend" / "src" / "lib" / "api" / "schema.d.ts"
    assert schema.is_file(), "Thiếu frontend/src/lib/api/schema.d.ts — chạy `npm run gen:api` trong frontend/"
    text = schema.read_text(encoding="utf-8")
    assert "auto-generated by openapi-typescript" in text
    assert '"/api/v1/resident/quotes"' in text


def test_error_envelope_is_documented_for_the_frontend():
    spec = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
    schemas = spec["components"]["schemas"]
    assert {"ErrorResponse", "ErrorCode", "ReadinessReport"} <= set(schemas)
    responses = spec["paths"]["/api/v1/resident/queue"]["get"]["responses"]
    assert responses["501"]["content"]["application/json"]["schema"]["$ref"].endswith("/ErrorResponse")


def test_every_websocket_payload_model_is_in_openapi():
    """WS không tự có trên OpenAPI: mọi model payload phải đã xuất hiện qua một endpoint REST để web có type."""
    schemas = set(json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))["components"]["schemas"])
    assert set(WS_PAYLOAD_MODELS) == set(WsMessageType), "Thêm WsMessageType phải khai báo payload ở WS_PAYLOAD_MODELS"
    missing = {model.__name__ for models in WS_PAYLOAD_MODELS.values() for model in models} - schemas
    assert not missing, f"Model payload WebSocket chưa có trên OpenAPI: {sorted(missing)}"


def test_no_schema_exposes_password_or_email_of_other_users():
    """UserRecord (có password_hash) không bao giờ được thành response model."""
    spec_text = SNAPSHOT_PATH.read_text(encoding="utf-8")
    assert "password_hash" not in spec_text
    assert "UserRecord" not in spec_text
